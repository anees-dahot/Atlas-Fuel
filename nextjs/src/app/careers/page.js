export async function generateMetadata() {
  return loadPageMetadata({
    getPage: getCareersPage,
    getSiteSettings,
    path: '/careers',
    fallbackTitle: 'Careers | Atlas Fuel Australia',
    fallbackDescription: fallbackData.heroDescription,
    fallbackImage: fallbackData.heroImageUrl,
  })
}

const fallbackSiteSettings = {
  ctaBannerHeading: 'Ready to Join Our Team?',
  ctaBannerText: 'Explore our current openings and discover how you can build a rewarding career with Atlas Fuel.',
  ctaBannerButtonText: 'View Openings',
  ctaBannerButtonLink: '#openings',
}

export default async function CareersPage() {
  const [sanity, siteSettings] = await Promise.all([
    getCareersPage().catch(() => null),
    getSiteSettings().catch(() => null),
  ])

  const data = mergeWithFallback(fallbackData, sanity)
  const settings = mapPageCta(sanity, siteSettings, fallbackSiteSettings)

  return (
    <>
      <CareersClient data={data} siteSettings={settings} />
    </>
  )
}
